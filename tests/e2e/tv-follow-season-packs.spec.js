import { test, expect } from '@playwright/test';

test.skip(process.env.CP_TV_E2E !== '1', 'Requires disposable TV fixture server');
for (const width of [1366, 1920]) {
  test(`season packs keep manual review and real Follow/import at desktop ${width}`, async ({page,request}) => {
    await page.setViewportSize({width,height:width===1366?768:1080});
    const setup = await request.post('/__tv_fixture/season-pack/begin',{data:{mode:'pack'}});
    expect(setup.ok()).toBeTruthy();
    const fixture = await setup.json();
    await page.goto(`/tv/series/${fixture.series_id}`);
    const download = page.getByRole('button',{name:'Download season',exact:true});
    await download.click();
    const dialog = page.getByRole('dialog',{name:'TV release review'});
    await dialog.getByLabel('Download quality profile').selectOption('cp-compatibility');
    await expect(dialog).toContainText('1 selected releases · 3 of 3 episodes');
    await expect(dialog).toContainText('Season pack');
    await expect(dialog.getByRole('button',{name:'Confirm this is the selected series'})).toBeVisible();
    await dialog.getByRole('checkbox',{name:/Show blocked releases/}).check();
    const wrong = dialog.locator('.tv-release-row').filter({hasText:'.2010.S01.'});
    await expect(wrong.getByRole('checkbox')).toBeDisabled();
    expect(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
    await page.screenshot({path:`docs/verification/tv-follow-season-packs/review-${width}.png`});
    await page.keyboard.press('Escape');
    await expect(dialog).toHaveCount(0);
    await expect(download).toBeFocused();
    const follow = page.getByRole('region',{name:'Follow and download'});
    await follow.getByLabel('Follow quality profile').selectOption('cp-compatibility');
    await follow.getByRole('button',{name:'Preview targets',exact:true}).click();
    await expect(follow).toContainText('3 target episodes');
    await follow.getByRole('button',{name:'Save draft',exact:true}).click();
    const started = page.waitForResponse(response=>response.url().endsWith('/start') && response.request().method()==='POST');
    await follow.getByRole('button',{name:'Start',exact:true}).click();
    expect((await started).ok()).toBeTruthy();
    const run = await request.post(`/__tv_fixture/season-pack/run/${fixture.series_id}`);
    expect(run.ok()).toBeTruthy();
    const outcome = await run.json();
    expect(outcome.queries.at(-1).episode).toBeNull();
    expect(outcome.tasks[0].counts.queued).toBe(3);
    expect(new Set(outcome.tasks[0].episodes.map(row=>row.intent_id)).size).toBe(1);
    await page.reload();
    await expect(follow).toContainText('3 queued');
    await page.screenshot({path:`docs/verification/tv-follow-season-packs/queued-${width}.png`});
    const completed = await request.post(`/__tv_fixture/season-pack/complete/${fixture.series_id}`);
    expect(completed.ok()).toBeTruthy();
    const imported = await completed.json();
    expect(imported.job.state).toBe('imported');
    expect(imported.source_exists).toBe(false);
    expect(imported.episodes.every(row=>row.available)).toBe(true);
    await page.reload();
    await expect(follow).toContainText('No active tasks');
    const episode = page.getByRole('article',{name:/S02E01/});
    await episode.getByRole('button',{name:'Versions (1)',exact:true}).click();
    await expect(page.getByRole('dialog',{name:/S02E01 versions/})).toContainText('1080p');
    await page.keyboard.press('Escape');
    await page.goto('/discover');
    await page.goBack();
    await expect(episode).toContainText('Available locally');
    await page.goForward();
    await page.goBack();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  });
}

test('source review shows attributed reasons and reuses the existing confirmation dialog',async ({page,request})=>{
  const fixture = await (await request.post('/__tv_fixture/season-pack/begin',{data:{mode:'review'}})).json();
  const saved = await request.post(`/api/tv/series/${fixture.series_id}/tasks`,{data:{scope:'season',season:2,action:'missing',profile_id:'cp-compatibility'}});
  expect(saved.ok()).toBeTruthy();
  const draft = await saved.json();
  expect((await request.post(`/api/tv/tasks/${draft.id}/start`,{data:{}})).ok()).toBeTruthy();
  const run = await request.post(`/__tv_fixture/season-pack/run/${fixture.series_id}`);
  expect(run.ok()).toBeTruthy();
  await page.goto(`/tv/series/${fixture.series_id}`);
  const follow = page.getByRole('region',{name:'Follow and download'});
  await expect(follow).toContainText('3 needs review');
  await expect(follow).toContainText('Review required; next automatic search');
  await follow.getByText('Source search details',{exact:true}).first().click();
  await expect(follow).toContainText('Fixture TV');
  await expect(follow).toContainText('Some indexers did not finish');
  await follow.getByRole('button',{name:'Review season releases',exact:true}).first().click();
  const dialog = page.getByRole('dialog',{name:'TV release review'});
  await dialog.getByRole('button',{name:'Confirm this is the selected series'}).click();
  await expect(dialog.getByRole('button',{name:'Download selected releases'})).toBeEnabled();
  await page.screenshot({path:'docs/verification/tv-follow-season-packs/source-review.png'});
  await page.keyboard.press('Escape');
  await expect(follow.getByRole('button',{name:'Review season releases'}).first()).toBeFocused();
});
